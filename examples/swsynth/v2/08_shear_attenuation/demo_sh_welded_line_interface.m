% Antiplane SH line source interacting with welded elastic half-spaces.
root=fileparts(fileparts(fileparts(fileparts(fileparts(mfilename("fullpath"))))));
addpath(fullfile(root,"src"));

p=struct( ...
    "x_m", -0.025:0.0005:0.025, ...
    "z_m", (-0.025:0.0005:0.025).', ...
    "source_xz_m", [-0.035 0.00013], ...
    "interface_x_m", 0, ...
    "frequency_hz", 300, ...
    "cs1_m_s", 2, ...
    "cs2_m_s", 3, ...
    "rho1_kg_m3", 1000, ...
    "rho2_kg_m3", 1000, ...
    "interface_enabled", true, ...
    "spectral_count", 3500, ...
    "spectral_step_rad_m", 2);

on=swsynth.propagation.interface.lineSHWeldedInterface(p);

p.interface_enabled=false;
off=swsynth.propagation.interface.lineSHWeldedInterface(p);

fields={on.incident_uy_zx,on.reflected_uy_zx, ...
    on.transmitted_uy_zx,on.total_uy_zx,off.total_uy_zx};

names={"Incident (Hankel)","Reflected (angular spectrum)", ...
    "Transmitted (angular spectrum)","Total interface ON", ...
    "No interface reference"};

figure("Name","Welded SH line source interface");
tiledlayout(2,3);

for j=1:5
    nexttile;
    imagesc(on.x_m*1000,on.z_m*1000,real(fields{j}));
    axis image;
    axis xy;
    colorbar;
    xline(0,"k--");
    title(names{j});
    xlabel("x (mm)");
    ylabel("z (mm)");
end

fprintf("FoV = %.1f mm x %.1f mm\n", ...
    1000*(max(on.x_m)-min(on.x_m)), ...
    1000*(max(on.z_m)-min(on.z_m)));
fprintf("Source at x = %.1f mm, z = %.3f mm\n", ...
    1000*p.source_xz_m(1),1000*p.source_xz_m(2));
fprintf("Angular spectrum max tangential k %.2f rad/m, step %.2f rad/m\n", ...
    on.spectral_max_rad_m,on.spectral_step_rad_m);

on=swsynth.propagation.interface.lineSHWeldedInterface(p);
p.interface_enabled=false;
off=swsynth.propagation.interface.lineSHWeldedInterface(p);
