%% Local functions

function [centers, profile] = ...
        radialAnnularMean(powerZX, normalizedRadiusZX, edges)

centers = 0.5 .* (edges(1:end-1) + edges(2:end));
profile = nan(size(centers));

for binIndex = 1:numel(centers)
    mask = ...
        normalizedRadiusZX >= edges(binIndex) & ...
        normalizedRadiusZX < edges(binIndex + 1);

    if any(mask(:))
        profile(binIndex) = mean(powerZX(mask));
    end
end

end

function normalizedProfile = ...
        normalizeRadialDensity(radius, profile)

validMask = isfinite(profile);

normalization = trapz( ...
    radius(validMask), ...
    profile(validMask) .* radius(validMask));

normalizedProfile = profile ./ normalization;

end

function [centers, profile] = angularAnnularMean( ...
    powerZX, normalizedRadiusZX, angleZX, ...
    minimumRadius, maximumRadius, edges)

centers = 0.5 .* (edges(1:end-1) + edges(2:end));
profile = nan(size(centers));

annulusMask = ...
    normalizedRadiusZX >= minimumRadius & ...
    normalizedRadiusZX <= maximumRadius;

for binIndex = 1:numel(centers)
    mask = ...
        annulusMask & ...
        angleZX >= edges(binIndex) & ...
        angleZX < edges(binIndex + 1);

    if any(mask(:))
        profile(binIndex) = mean(powerZX(mask));
    end
end

end
