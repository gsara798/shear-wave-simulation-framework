%% Projected-3D scalar versus axial ensemble spectrum
%
% This diagnostic distinguishes:
%
% 1. A scalar projected-3D field with equal directional power.
% 2. Axial shear motion with random transverse polarization.
%
% Independent random initial phases imply
%
%   E[|sum_n a_n exp(i phi_n) F_n|^2]
%       = sum_n E[|a_n|^2] |F_n|^2.
%
% Therefore the ensemble power spectrum can be calculated exactly without
% finite Monte Carlo phase noise.
%
% For a random polarization angle perpendicular to u:
%
%   E[p_z^2 | u] = (1 - u_z^2)/2.

clear;
close all;

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));

addpath(fullfile(repositoryRoot, "src"));

outputDirectory = fullfile( ...
    repositoryRoot, ...
    "outputs", ...
    "diagnostics", ...
    "projected3d_axial_ensemble");

if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

%% Configuration

directionCount = 128;

domainLengthXM = 0.050;
domainLengthZM = 0.050;

dxM = 0.00025;
dzM = 0.00025;

frequencyHz = 250;
csMps = 2.0;

omegaRadS = 2*pi*frequencyHz;
referenceWavenumberRadM = omegaRadS / csMps;

cfg = swsynth.defaultConfig();

cfg.seed = 7301;

cfg.domain.Lx_m = domainLengthXM;
cfg.domain.Lz_m = domainLengthZM;
cfg.domain.dx_m = dxM;
cfg.domain.dz_m = dzM;

cfg.medium.background_cs_m_s = csMps;
cfg.medium.objects = {};

cfg.wavefield.frequency_hz = frequencyHz;

cfg.directions.count = directionCount;
cfg.directions.space = "three_dimensional";
cfg.directions.sampling_method = "fibonacci";
cfg.directions.require_in_plane = false;
cfg.directions.support.type = "full_sphere";

cfg.execution.use_parallel = false;

[cfg, ~] = swsynth.validateConfig(cfg);

maps = swsynth.buildMediumMaps(cfg);
directions = swsynth.generateDirections(cfg);

xM = maps.x_m;
zM = maps.z_m;

directionsXYZ = double([
    directions.ux(:), ...
    directions.uy(:), ...
    directions.uz(:)]);

Nx = numel(xM);
Nz = numel(zM);

%% One scalar and one axial realization

rng(8301);

initialPhaseRad = ...
    2*pi*rand(directionCount, 1);

scalarWeights = ...
    exp(1i .* initialPhaseRad) ./ ...
    sqrt(directionCount);

rng(8302);

[polarizationXYZ, polarizationDiagnostics] = ...
    swsynth.propagation.projected3d. ...
        sampleTransversePolarization( ...
            directionsXYZ);

axialWeights = ...
    polarizationXYZ(:, 3) .* ...
    exp(1i .* initialPhaseRad) ./ ...
    sqrt(directionCount);

fieldOptions = struct();
fieldOptions.UseParallel = false;

scalarFieldZX = ...
    swsynth.propagation.projected3d. ...
        synthesizeDirectionalField( ...
            maps.cs_map_zx, ...
            xM, ...
            zM, ...
            directionsXYZ, ...
            scalarWeights, ...
            frequencyHz, ...
            csMps, ...
            fieldOptions);

axialFieldZX = ...
    swsynth.propagation.projected3d. ...
        synthesizeDirectionalField( ...
            maps.cs_map_zx, ...
            xM, ...
            zM, ...
            directionsXYZ, ...
            axialWeights, ...
            frequencyHz, ...
            csMps, ...
            fieldOptions);

%% Window and spectral coordinates

windowX = ...
    0.5 - 0.5*cos(2*pi*(0:Nx-1)/(Nx-1));

windowZ = ...
    0.5 - 0.5*cos(2*pi*(0:Nz-1)/(Nz-1));

windowZX = windowZ(:) * windowX(:).';

fftSizeX = 2 * 2^nextpow2(Nx);
fftSizeZ = 2 * 2^nextpow2(Nz);

kxRadM = ...
    2*pi .* ...
    ((-floor(fftSizeX/2)):(ceil(fftSizeX/2)-1)) ./ ...
    (fftSizeX * dxM);

kzRadM = ...
    2*pi .* ...
    ((-floor(fftSizeZ/2)):(ceil(fftSizeZ/2)-1)) ./ ...
    (fftSizeZ * dzM);

[KXRadM, KZRadM] = meshgrid( ...
    kxRadM, ...
    kzRadM);

normalizedRadiusZX = ...
    hypot(KXRadM, KZRadM) ./ ...
    referenceWavenumberRadM;

spectralAngleZX = atan2( ...
    KZRadM, ...
    KXRadM);

%% Exact random-phase ensemble spectra

scalarEnsemblePowerZX = ...
    zeros(fftSizeZ, fftSizeX);

axialEnsemblePowerZX = ...
    zeros(fftSizeZ, fftSizeX);

expectedAxialPowerByDirection = ...
    (1 - directionsXYZ(:, 3).^2) ./ 2;

timerHandle = tic;

for directionIndex = 1:directionCount

    phaseDelayZX = ...
        swsynth.propagation.projected3d. ...
            computeDirectionalPhaseDelay( ...
                maps.cs_map_zx, ...
                xM, ...
                zM, ...
                directionsXYZ(directionIndex, :), ...
                csMps);

    directionalFieldZX = ...
        exp(1i .* omegaRadS .* phaseDelayZX);

    directionalSpectrumZX = fftshift(fft2( ...
        directionalFieldZX .* windowZX, ...
        fftSizeZ, ...
        fftSizeX));

    directionalPowerZX = ...
        abs(directionalSpectrumZX).^2;

    scalarEnsemblePowerZX = ...
        scalarEnsemblePowerZX + ...
        directionalPowerZX ./ directionCount;

    axialEnsemblePowerZX = ...
        axialEnsemblePowerZX + ...
        expectedAxialPowerByDirection(directionIndex) .* ...
        directionalPowerZX ./ directionCount;

    if mod(directionIndex, 16) == 0
        fprintf( ...
            "Processed %d / %d directions.\n", ...
            directionIndex, ...
            directionCount);
    end
end

ensembleRuntimeS = toc(timerHandle);

%% Normalize spectra for visualization

scalarPowerDbZX = 10*log10( ...
    scalarEnsemblePowerZX ./ ...
    max(scalarEnsemblePowerZX(:)) + eps);

axialPowerDbZX = 10*log10( ...
    axialEnsemblePowerZX ./ ...
    max(axialEnsemblePowerZX(:)) + eps);

%% Radial spectral-density profiles

radialEdges = linspace(0, 0.96, 65);

[radialCenters, scalarRadialProfile] = ...
    radialAnnularMean( ...
        scalarEnsemblePowerZX, ...
        normalizedRadiusZX, ...
        radialEdges);

[~, axialRadialProfile] = ...
    radialAnnularMean( ...
        axialEnsemblePowerZX, ...
        normalizedRadiusZX, ...
        radialEdges);

scalarRadialTheory = ...
    1 ./ sqrt(1 - radialCenters.^2);

axialRadialTheory = ...
    (1 - 0.5*radialCenters.^2) ./ ...
    sqrt(1 - radialCenters.^2);

scalarRadialProfile = normalizeRadialDensity( ...
    radialCenters, ...
    scalarRadialProfile);

axialRadialProfile = normalizeRadialDensity( ...
    radialCenters, ...
    axialRadialProfile);

scalarRadialTheory = normalizeRadialDensity( ...
    radialCenters, ...
    scalarRadialTheory);

axialRadialTheory = normalizeRadialDensity( ...
    radialCenters, ...
    axialRadialTheory);

%% Angular profile in an outer annulus

angularMinimumRadius = 0.78;
angularMaximumRadius = 0.90;

angularEdges = linspace(-pi, pi, 73);

[angularCenters, scalarAngularProfile] = ...
    angularAnnularMean( ...
        scalarEnsemblePowerZX, ...
        normalizedRadiusZX, ...
        spectralAngleZX, ...
        angularMinimumRadius, ...
        angularMaximumRadius, ...
        angularEdges);

[~, axialAngularProfile] = ...
    angularAnnularMean( ...
        axialEnsemblePowerZX, ...
        normalizedRadiusZX, ...
        spectralAngleZX, ...
        angularMinimumRadius, ...
        angularMaximumRadius, ...
        angularEdges);

angularAnnulusMask = ...
    normalizedRadiusZX >= angularMinimumRadius & ...
    normalizedRadiusZX <= angularMaximumRadius;

representativeAngularRadius = mean( ...
    normalizedRadiusZX(angularAnnulusMask));

scalarAngularTheory = ...
    ones(size(angularCenters));

axialAngularTheory = ...
    1 - representativeAngularRadius^2 .* ...
    sin(angularCenters).^2;

scalarAngularProfile = ...
    scalarAngularProfile ./ ...
    mean(scalarAngularProfile, "omitnan");

axialAngularProfile = ...
    axialAngularProfile ./ ...
    mean(axialAngularProfile, "omitnan");

scalarAngularTheory = ...
    scalarAngularTheory ./ ...
    mean(scalarAngularTheory);

axialAngularTheory = ...
    axialAngularTheory ./ ...
    mean(axialAngularTheory);

%% Quantitative comparisons

centralMask = normalizedRadiusZX <= 0.35;

outerMask = ...
    normalizedRadiusZX >= 0.80 & ...
    normalizedRadiusZX <= 0.95;

horizontalOuterMask = ...
    outerMask & ...
    abs(cos(spectralAngleZX)) >= cosd(20);

verticalOuterMask = ...
    outerMask & ...
    abs(sin(spectralAngleZX)) >= cosd(20);

scalarCentralToOuterDensityRatio = ...
    mean(scalarEnsemblePowerZX(centralMask)) ./ ...
    mean(scalarEnsemblePowerZX(outerMask));

axialCentralToOuterDensityRatio = ...
    mean(axialEnsemblePowerZX(centralMask)) ./ ...
    mean(axialEnsemblePowerZX(outerMask));

axialHorizontalToVerticalRatio = ...
    mean(axialEnsemblePowerZX(horizontalOuterMask)) ./ ...
    mean(axialEnsemblePowerZX(verticalOuterMask));

totalAxialToScalarPowerRatio = ...
    sum(axialEnsemblePowerZX(:)) ./ ...
    sum(scalarEnsemblePowerZX(:));

expectedTotalAxialToScalarRatio = ...
    mean(expectedAxialPowerByDirection);

%% Figure

figureHandle = figure( ...
