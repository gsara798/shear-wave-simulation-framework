%% Projected-3D Eikonal bilayer diagnostic

clear;
close all;

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));

addpath(fullfile(repositoryRoot, "src"));

outputDirectory = fullfile( ...
    repositoryRoot, ...
    "outputs", ...
    "diagnostics", ...
    "projected3d_eikonal_bilayer");

if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

%% Configuration

dxM = 0.00025;
dzM = 0.00025;

xM = 0:dxM:0.050;
zM = (0:dzM:0.030).';

interfaceXM = 0.025;

incidentCsMps = 3.0;
transmittedCsMps = 2.0;

frequencyHz = 250;
omegaRadS = 2*pi*frequencyHz;

directionXYZ = [0.8, 0.6, 0];

csMapZX = incidentCsMps * ...
    ones(numel(zM), numel(xM));

csMapZX(:, xM > interfaceXM) = ...
    transmittedCsMps;

%% Phase delay

[phaseDelayZX, diagnostics] = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, ...
            xM, ...
            zM, ...
            directionXYZ, ...
            incidentCsMps);

%% Axial polarization realization

rng(9101);

polarizationXYZ = ...
    swsynth.propagation.projected3d. ...
        sampleTransversePolarization(directionXYZ);

axialWeight = polarizationXYZ(3);

fieldZX = ...
    axialWeight .* ...
    exp(1i .* omegaRadS .* phaseDelayZX);

%% Local projected wavenumber

[delayGradientX, delayGradientZ] = gradient( ...
    phaseDelayZX, ...
    dxM, ...
    dzM);

localKxZX = omegaRadS .* delayGradientX;
localKzZX = omegaRadS .* delayGradientZ;

localProjectedKZX = hypot( ...
    localKxZX, ...
    localKzZX);

%% Analytic projected wavenumbers

pySPerM = ...
    directionXYZ(2) / incidentCsMps;

expectedIncidentKRadM = ...
    omegaRadS * sqrt( ...
        1/incidentCsMps^2 - ...
        pySPerM^2);

expectedTransmittedKRadM = ...
    omegaRadS * sqrt( ...
        1/transmittedCsMps^2 - ...
        pySPerM^2);

%% Central patches on each side

patchSizePixels = 48;

centerZIndex = round(numel(zM)/2);

leftCenterXIndex = find( ...
    xM < interfaceXM, ...
    1, ...
    "last") - 30;

rightCenterXIndex = find( ...
    xM > interfaceXM, ...
    1, ...
    "first") + 30;

halfPatch = floor(patchSizePixels/2);

patchZ = ...
    (centerZIndex-halfPatch+1):(centerZIndex+halfPatch);

leftPatchX = ...
    (leftCenterXIndex-halfPatch+1):(leftCenterXIndex+halfPatch);

rightPatchX = ...
    (rightCenterXIndex-halfPatch+1):(rightCenterXIndex+halfPatch);

leftPatchZX = ...
    fieldZX(patchZ, leftPatchX);

rightPatchZX = ...
    fieldZX(patchZ, rightPatchX);

windowVector = ...
    0.5 - ...
    0.5*cos( ...
        2*pi*(0:patchSizePixels-1)/(patchSizePixels-1));

windowZX = ...
    windowVector(:) * windowVector(:).';

fftSize = 4 * 2^nextpow2(patchSizePixels);

leftSpectrum = fftshift(fft2( ...
    leftPatchZX .* windowZX, ...
    fftSize, ...
    fftSize));

rightSpectrum = fftshift(fft2( ...
    rightPatchZX .* windowZX, ...
    fftSize, ...
    fftSize));

leftPower = abs(leftSpectrum).^2;
rightPower = abs(rightSpectrum).^2;

leftPower = leftPower ./ max(leftPower(:));
rightPower = rightPower ./ max(rightPower(:));

kAxisRadM = ...
    2*pi .* ...
    ((-floor(fftSize/2)):(ceil(fftSize/2)-1)) ./ ...
    (fftSize * dxM);

referenceK0RadM = ...
    omegaRadS / incidentCsMps;

normalizedKAxis = ...
    kAxisRadM ./ referenceK0RadM;

%% Numerical summaries

leftRegion = xM < interfaceXM - 0.005;
rightRegion = xM > interfaceXM + 0.005;

measuredIncidentKRadM = mean( ...
    localProjectedKZX(:, leftRegion), ...
    "all");

measuredTransmittedKRadM = mean( ...
    localProjectedKZX(:, rightRegion), ...
    "all");

incidentRelativeError = ...
    abs( ...
        measuredIncidentKRadM - ...
        expectedIncidentKRadM) ./ ...
    expectedIncidentKRadM;

transmittedRelativeError = ...
    abs( ...
        measuredTransmittedKRadM - ...
        expectedTransmittedKRadM) ./ ...
    expectedTransmittedKRadM;

%% Figure

figureHandle = figure( ...
    "Visible", "off", ...
    "Color", "w", ...
    "Position", [50, 50, 1500, 950]);

tiledlayout( ...
    2, ...
    3, ...
    "TileSpacing", "compact", ...
    "Padding", "compact");

nexttile;

imagesc(xM*1e3, zM*1e3, csMapZX);
axis image;
set(gca, "YDir", "normal");
colorbar;

xline(interfaceXM*1e3, "w--", "LineWidth", 1.5);

xlabel("x (mm)");
ylabel("z (mm)");
title("Shear-wave speed (m/s)");

nexttile;

imagesc(xM*1e3, zM*1e3, phaseDelayZX*1e3);
axis image;
set(gca, "YDir", "normal");
colorbar;

xline(interfaceXM*1e3, "w--", "LineWidth", 1.5);

xlabel("x (mm)");
ylabel("z (mm)");
title("Projected-3D phase delay (ms)");

nexttile;

imagesc(xM*1e3, zM*1e3, real(fieldZX));
axis image;
set(gca, "YDir", "normal");
colorbar;

xline(interfaceXM*1e3, "w--", "LineWidth", 1.5);

xlabel("x (mm)");
ylabel("z (mm)");
title("Axial motion: Real(U_z)");

nexttile;

imagesc( ...
    xM*1e3, ...
    zM*1e3, ...
    localProjectedKZX/1e3);

axis image;
set(gca, "YDir", "normal");
colorbar;

xline(interfaceXM*1e3, "w--", "LineWidth", 1.5);

xlabel("x (mm)");
ylabel("z (mm)");
title("Local projected k (rad/mm)");

nexttile;

imagesc( ...
    normalizedKAxis, ...
    normalizedKAxis, ...
    leftPower);

axis image;
set(gca, "YDir", "normal");
clim([0, 1]);
xlim([-2, 2]);
ylim([-2, 2]);
colorbar;

xlabel("k_x / k_{0,left}");
ylabel("k_z / k_{0,left}");
title("Left patch spectrum");

nexttile;

imagesc( ...
    normalizedKAxis, ...
    normalizedKAxis, ...
    rightPower);

axis image;
set(gca, "YDir", "normal");
clim([0, 1]);
xlim([-2, 2]);
ylim([-2, 2]);
colorbar;

xlabel("k_x / k_{0,left}");
ylabel("k_z / k_{0,left}");
title("Right patch spectrum");

sgtitle(sprintf( ...
    ["Projected-3D bilayer | c_1=%.1f m/s | " + ...
     "c_2=%.1f m/s | u=[%.1f %.1f %.1f]"], ...
    incidentCsMps, ...
    transmittedCsMps, ...
    directionXYZ));

figurePath = fullfile( ...
    outputDirectory, ...
    "projected3d_bilayer.png");

exportgraphics( ...
    figureHandle, ...
    figurePath, ...
    "Resolution", 180);

close(figureHandle);

%% Summary

summaryTable = table( ...
    incidentCsMps, ...
    transmittedCsMps, ...
    frequencyHz, ...
    pySPerM, ...
    expectedIncidentKRadM, ...
    measuredIncidentKRadM, ...
    incidentRelativeError, ...
    expectedTransmittedKRadM, ...
    measuredTransmittedKRadM, ...
    transmittedRelativeError, ...
    diagnostics.solver.iterations, ...
    VariableNames=[ ...
        "incident_cs_m_s", ...
        "transmitted_cs_m_s", ...
        "frequency_hz", ...
        "py_s_m", ...
        "expected_incident_k_rad_m", ...
        "measured_incident_k_rad_m", ...
        "incident_relative_error", ...
        "expected_transmitted_k_rad_m", ...
        "measured_transmitted_k_rad_m", ...
        "transmitted_relative_error", ...
        "solver_iterations"]);

summaryPath = fullfile( ...
    outputDirectory, ...
    "summary.csv");

writetable(summaryTable, summaryPath);

disp(summaryTable);

fprintf("\nExpected incident k    : %.6f rad/m\n", ...
    expectedIncidentKRadM);

fprintf("Measured incident k    : %.6f rad/m\n", ...
    measuredIncidentKRadM);

fprintf("Expected transmitted k : %.6f rad/m\n", ...
    expectedTransmittedKRadM);

fprintf("Measured transmitted k : %.6f rad/m\n", ...
    measuredTransmittedKRadM);

fprintf("Saved figure: %s\n", figurePath);
