function testOppositeYDirectionsGiveSameObservedPhaseDelay(testCase)

xM = 0:0.001:0.020;
zM = (0:0.001:0.020).';

csMps = 3.0;
csMapZX = csMps * ones(numel(zM), numel(xM));

positiveY = [0.48, 0.60, 0.64];
negativeY = [0.48, -0.60, 0.64];

phasePositiveY = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, xM, zM, positiveY, csMps);

phaseNegativeY = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, xM, zM, negativeY, csMps);

verifyEqual( ...
    testCase, ...
    phaseNegativeY, ...
    phasePositiveY, ...
    "AbsTol", 1e-12);

end

function testMoreOutOfPlaneDirectionHasSmallerPhaseGradient(testCase)

xM = 0:0.001:0.030;
zM = (0:0.001:0.020).';

csMps = 2.0;
csMapZX = csMps * ones(numel(zM), numel(xM));

mostlyInPlane = [sqrt(0.96), 0.20, 0];
mostlyOutOfPlane = [0.60, 0.80, 0];

phaseInPlane = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, xM, zM, mostlyInPlane, csMps);

phaseOutOfPlane = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, xM, zM, mostlyOutOfPlane, csMps);

gradientInPlane = mean(diff(phaseInPlane, 1, 2), "all");
gradientOutOfPlane = mean(diff(phaseOutOfPlane, 1, 2), "all");

verifyLessThan( ...
    testCase, ...
    gradientOutOfPlane, ...
    gradientInPlane);

end

function testPureOutOfPlaneDirectionIsSpatiallyConstant(testCase)

xM = 0:0.001:0.010;
zM = (0:0.001:0.012).';

csMapZX = 2.5 * ones(numel(zM), numel(xM));

[phaseDelayZX, diagnostics] = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, ...
            xM, ...
            zM, ...
            [0, 1, 0], ...
            2.5);

verifyEqual( ...
    testCase, ...
    phaseDelayZX, ...
    zeros(size(csMapZX)), ...
    "AbsTol", 0);

verifyEqual( ...
    testCase, ...
    diagnostics.solver.method, ...
    "pure_out_of_plane_exact");

end

function testBoundaryConditionFixesCorrectInflowEdges(testCase)

xM = 0:0.001:0.010;
zM = (0:0.001:0.008).';

[~, fixedMaskZX, diagnostics] = ...
    swsynth.propagation.projected3d. ...
        buildIncidentBoundaryCondition( ...
            xM, ...
            zM, ...
            [0.48, 0.60, -0.64], ...
            2.0);

verifyTrue(testCase, all(fixedMaskZX(:, 1)));
verifyTrue(testCase, all(fixedMaskZX(end, :)));

verifyFalse( ...
    testCase, ...
    any(fixedMaskZX(1, 2:end)));

verifyFalse( ...
    testCase, ...
    any(fixedMaskZX(1:end-1, end)));

verifyEqual( ...
    testCase, ...
    diagnostics.mode, ...
    "directional_inflow");

end
