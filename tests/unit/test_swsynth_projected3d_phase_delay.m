function tests = test_swsynth_projected3d_phase_delay
%TEST_SWSYNTH_PROJECTED3D_PHASE_DELAY Directional Eikonal tests.

tests = functiontests(localfunctions);

end

function testPositiveProjectedDirectionMatchesHomogeneousPlaneWave(testCase)

xM = 0:0.0005:0.020;
zM = (0:0.0007:0.014).';

csMps = 2.0;
csMapZX = csMps * ones(numel(zM), numel(xM));

% Unit vector: 0.48^2 + 0.60^2 + 0.64^2 = 1.
directionXYZ = [0.48, 0.60, 0.64];

[phaseDelayZX, diagnostics] = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, ...
            xM, ...
            zM, ...
            directionXYZ, ...
            csMps);

[X, Z] = meshgrid(xM, zM);

expectedZX = ...
    directionXYZ(1) .* X ./ csMps + ...
    directionXYZ(3) .* Z ./ csMps;

verifyEqual( ...
    testCase, ...
    phaseDelayZX, ...
    expectedZX, ...
    "AbsTol", 1e-10);

verifyTrue(testCase, diagnostics.solver.converged);
verifyEqual( ...
    testCase, ...
    diagnostics.solver.method, ...
    "homogeneous_exact");
verifyEqual(testCase, diagnostics.solver.iterations, 0);

end

