function testPointForcePreservesAngularRadiationMagnitude(testCase)
request=struct("model","point_force_shear_far_field", ...
    "geometry","projected3d", ...
    "source_xyz_m",[0 0 0], ...
    "observation_xyz_m",[1 0 0;0 0 1;1 0 1], ...
    "force_direction_xyz",[1 0 0]);
out=swsynth.polarization.compute(request);
verifyEqual(testCase,out.vector_xyz(1,:),[0 0 0],"AbsTol",1e-14);
verifyEqual(testCase,out.vector_xyz(2,:),[1 0 0],"AbsTol",1e-14);
verifyEqual(testCase,out.magnitude(1:2),[0;1],"AbsTol",1e-14);
verifyEqual(testCase,out.unit_vector_xyz(1,:),[0 0 0]);
verifyEqual(testCase,out.distance_m,[1;1;sqrt(2)],"AbsTol",1e-14);
verifyEqual(testCase,out.diagnostics.maximum_transversality_error, ...
    0,"AbsTol",1e-14);
end

function testPointForceAgreesWithLegacyProjection(testCase)
source=[.01 -.015 .02];
obs=[.02 -.01 .03;.01 .03 .04;.03 0 .015];
force=[1 0 1];
axis=[0 0 1];
request=struct("model","point_force_shear_far_field", ...
    "geometry","volumetric3d", ...
    "source_xyz_m",source,"observation_xyz_m",obs, ...
    "force_direction_xyz",force);
out=swsynth.polarization.compute(request);
[projection,p,radial,distance]= ...
    swsynth.propagation.spherical.point_source. ...
        shear_far_field.computeShearProjection(source,obs,force,axis);
verifyEqual(testCase,out.vector_xyz,p,"AbsTol",1e-14);
verifyEqual(testCase,out.radial_direction_xyz,radial,"AbsTol",1e-14);
verifyEqual(testCase,out.distance_m,distance,"AbsTol",1e-14);
verifyEqual(testCase,out.vector_xyz*axis.',projection,"AbsTol",1e-14);
end

