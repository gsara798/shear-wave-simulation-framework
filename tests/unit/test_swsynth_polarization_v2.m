function tests=test_swsynth_polarization_v2
tests=functiontests(localfunctions);
end

function testPlanarSVTransverse(testCase)
request=struct("model","plane_wave","geometry","2d", ...
    "policy","in_plane_sv", ...
    "direction_xyz",[1 0 0;0 0 1;1 0 1]);
p=swsynth.polarization.compute(request);
verifyEqual(testCase,p.vector_xyz(:,2),zeros(3,1));
verifyEqual(testCase,vecnorm(p.vector_xyz,2,2),ones(3,1), ...
    "AbsTol",1e-14);
verifyEqual(testCase,sum(p.vector_xyz.*p.direction_xyz,2), ...
    zeros(3,1),"AbsTol",1e-14);
verifyEqual(testCase,p.vector_xyz(1,:),[0 0 -1]);
end

function testPlanarRandomPolarizationStaysInPlane(testCase)
request=struct("model","plane_wave","geometry","planar2d", ...
    "policy","transverse_random", ...
    "direction_xyz",repmat([1 0 0],12,1), ...
    "stream",RandStream("mt19937ar","Seed",53053));
state=rng;
a=swsynth.polarization.compute(request);
verifyEqual(testCase,rng,state);
request.stream=RandStream("mt19937ar","Seed",53053);
b=swsynth.polarization.compute(request);
verifyEqual(testCase,a,b);
verifyEqual(testCase,a.vector_xyz(:,1:2),zeros(12,2), ...
    "AbsTol",1e-14);
verifyEqual(testCase,abs(a.vector_xyz(:,3)),ones(12,1));
end

