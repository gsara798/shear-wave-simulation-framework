function tests = test_swsynth_phase_compatibility_central
tests = functiontests(localfunctions);
end

function testPlaneAnalytical(testCase)
verifyEqual(testCase,swsynth.phase.validateCompatibility( ...
    "plane_wave","analytical","projected3d",false), ...
    "homogeneous_projected_3d");
verifyError(testCase,@() swsynth.phase.validateCompatibility( ...
    "plane_wave","analytical","projected3d",true), ...
    "swsynth:PlaneWaveRequiresHomogeneousMedium");
end

function testVolumetricAnalytical(testCase)
verifyEqual(testCase,swsynth.phase.validateCompatibility( ...
    "plane_wave","analytical","volumetric3d",false), ...
    "homogeneous_plane_3d");
verifyError(testCase,@() swsynth.phase.validateCompatibility( ...
    "plane_wave","analytical","volumetric3d",true), ...
    "swsynth:HomogeneousAnalytic3DRequiresUniformMedium");
end

function testEikonalAcceptsHeterogeneity(testCase)
verifyEqual(testCase,swsynth.phase.validateCompatibility( ...
    "plane_wave","eikonal","projected3d",true), ...
    "projected3d_directional_eikonal");
verifyEqual(testCase,swsynth.phase.validateCompatibility( ...
    "plane_wave","eikonal","volumetric3d",true), ...
    "volumetric_eikonal_3d");
end

function testUnsupportedPhysical2DAndSpherical(testCase)
verifyError(testCase,@() swsynth.phase.validateCompatibility( ...
    "plane_wave","eikonal","2d",false), ...
    "swsynth:PhaseRoutingUnsupported");
verifyError(testCase,@() swsynth.phase.validateCompatibility( ...
    "spherical_wave","eikonal","volumetric3d",false), ...
    "swsynth:PhaseRoutingUnsupported");
end
