function requireV2Config(config)
%REQUIREV2CONFIG Reject legacy swsynth JSON at all public entry points.
% The historical implementation is preserved in the backup worktree.
arguments
    config (1,1) struct
end
if ~isfield(config,"schema_version") || ...
        ~isscalar(string(config.schema_version)) || ...
        string(config.schema_version)~="2.0"
    error("swsynth:LegacyConfigUnsupported", ...
        ["The develop/v2 swsynth backend requires a schema_version " + ...
         "'2.0' scenario. Legacy configurations must be run from the " + ...
         "preserved worktree or explicitly converted; the old physical " + ...
         "model is not silently substituted."]);
end
end
