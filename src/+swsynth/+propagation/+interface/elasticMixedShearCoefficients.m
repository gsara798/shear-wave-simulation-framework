function out=elasticMixedShearCoefficients(request)
%ELASTICMIXEDSHEARCOEFFICIENTS Arbitrary transverse incident S polarization.
% Local interface frame: normal +x, incidence plane x-z, SH along +y.
% SH and SV decouple in isotropic elastic media. P conversion comes only
% from SV. Coefficients are dimensionless displacement amplitudes.
arguments
    request (1,1) struct
end
if ~isfield(request,"shear_polarization_xyz")
    error("swsynth:MixedShearMissingPolarization", ...
        "Provide shear_polarization_xyz as an incident transverse unit vector.");
end
p=double(request.shear_polarization_xyz);
if ~isequal(size(p),[1 3]) || ~isreal(p) || ...
        any(~isfinite(p)) || norm(p)<=eps
    error("swsynth:MixedShearInvalidPolarization", ...
        "Polarization must be a finite nonzero xyz vector.");
end
p=p/norm(p);
theta=double(request.incidence_angle_rad);
if ~isscalar(theta)||~isfinite(theta)||theta<0||theta>=pi/2
    error("swsynth:MixedShearInvalidAngle","Incidence angle must lie in [0,pi/2).");
end
d=[cos(theta) 0 sin(theta)];
if abs(dot(d,p))>1e-10
    error("swsynth:MixedShearNontransverse", ...
        "Incident polarization must be perpendicular to propagation.");
end
eSH=[0 1 0];
eSV=[-sin(theta) 0 cos(theta)];
aSH=dot(p,eSH);aSV=dot(p,eSV);
sh=swsynth.propagation.interface.shCoefficients(struct( ...
    "frequency_hz",request.frequency_hz, ...
    "incidence_angle_rad",theta, ...
    "mu1_pa",request.rho1_kg_m3*request.cs1_m_s^2, ...
    "rho1_kg_m3",request.rho1_kg_m3, ...
    "mu2_pa",request.rho2_kg_m3*request.cs2_m_s^2, ...
    "rho2_kg_m3",request.rho2_kg_m3));
sv=swsynth.propagation.interface.psvElasticCoefficients(request);
out=struct("model","elastic_mixed_SH_SV_incident", ...
    "incident_polarization_xyz",p, ...
    "incident_SH_amplitude",aSH,"incident_SV_amplitude",aSV, ...
    "SH",sh,"PSV",sv, ...
    "reflected_SH_amplitude",aSH*sh.reflection_displacement, ...
    "transmitted_SH_amplitude",aSH*sh.transmission_displacement, ...
    "reflected_SV_amplitude",aSV*sv.reflection_SV_displacement, ...
    "transmitted_SV_amplitude",aSV*sv.transmission_SV_displacement, ...
    "reflected_P_amplitude",aSV*sv.reflection_P_displacement, ...
    "transmitted_P_amplitude",aSV*sv.transmission_P_displacement);
end
