function aperture = validate(aperture, sourcePositions, geometry, observationY)
%VALIDATE Check flattened aperture/source correspondence and coherence.
arguments
    aperture (1,1) struct
    sourcePositions (:,3) double {mustBeFinite}
    geometry (1,1) string
    observationY (1,1) double = 0
end
required=["source_count","node_count","node_count_per_source", ...
    "node_xyz_m","node_weight","node_source_id","per_source"];
for name=required
    if ~isfield(aperture,name)
        error("swsynth:InvalidApertureBundle", ...
            "Missing aperture field %s.",name);
    end
end
N=size(sourcePositions,1);
counts=double(aperture.node_count_per_source(:));
ids=double(aperture.node_source_id(:));
weights=double(aperture.node_weight(:));
xyz=double(aperture.node_xyz_m);
M=numel(ids);
if aperture.source_count~=N || numel(aperture.per_source)~=N || ...
        numel(counts)~=N || any(~isfinite(counts)) || ...
        any(counts~=floor(counts)) || any(counts<1) || ...
        aperture.node_count~=M || sum(counts)~=M || ...
        size(xyz,1)~=M || size(xyz,2)~=3 || ...
        numel(weights)~=M || any(~isfinite(weights)) || ...
        any(weights<0) || any(~isfinite(ids)) || ...
        any(ids~=floor(ids)) || any(ids<1) || any(ids>N)
    error("swsynth:InvalidApertureBundle", ...
        "Aperture nodes, counts, weights and source IDs are inconsistent.");
end
swsynth.sources.positions.validate(xyz,geometry,M,observationY);
expectedIds=repelem((1:N)',counts);
% MATLAB's repelem can return a row when the input is scalar (N=1).
% IDs from the aperture builder are always an M-by-1 column.
expectedIds=expectedIds(:);
if ~isequal(ids,expectedIds)
    error("swsynth:InvalidApertureBundle", ...
        "Aperture nodes must be grouped by parent source.");
end
for i=1:N
    source=aperture.per_source(i);
    mask=ids==i;
    if any(~isfinite(source.parent_source_xyz_m)) || ...
            ~isequal(size(source.parent_source_xyz_m),[1 3]) || ...
            norm(source.parent_source_xyz_m-sourcePositions(i,:))>1e-12 || ...
            source.node_count~=counts(i) || ...
            ~isequal(source.node_xyz_m,xyz(mask,:)) || ...
            any(abs(source.node_weights(:)-weights(mask))>1e-12) || ...
            abs(sum(weights(mask))-1)>1e-12
        error("swsynth:InvalidApertureBundle", ...
            "Aperture of source %d has inconsistent geometry or weights.",i);
    end
end
end
