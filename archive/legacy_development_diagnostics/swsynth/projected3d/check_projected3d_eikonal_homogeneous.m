%% Homogeneous projected-3D directional Eikonal diagnostic

clear;
close all;

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));

addpath(fullfile(repositoryRoot, "src"));

outputDirectory = fullfile( ...
    repositoryRoot, ...
    "outputs", ...
    "diagnostics", ...
    "projected3d_eikonal_homogeneous");

if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

%% Physical configuration

dxM = 0.00025;
dzM = 0.00025;

xM = 0:dxM:0.050;
zM = (0:dzM:0.050).';

csMps = 2.0;
frequencyHz = 250;
omegaRadS = 2*pi*frequencyHz;

% Unit direction:
% projected x-z norm = sqrt(0.48^2 + 0.64^2) = 0.8.
directionXYZ = [0.48, 0.60, 0.64];

csMapZX = csMps * ones(numel(zM), numel(xM));

%% Numerical projected-3D phase

tic;

[phaseDelayZX, diagnostics] = ...
    swsynth.propagation.projected3d. ...
        computeDirectionalPhaseDelay( ...
            csMapZX, ...
            xM, ...
            zM, ...
            directionXYZ, ...
            csMps);

runtimeS = toc;

fieldZX = exp(1i .* omegaRadS .* phaseDelayZX);

%% Homogeneous analytic solution

[X, Z] = meshgrid(xM, zM);

analyticPhaseDelayZX = ...
    directionXYZ(1) .* X ./ csMps + ...
    directionXYZ(3) .* Z ./ csMps;

phaseDelayErrorZX = ...
    phaseDelayZX - analyticPhaseDelayZX;

maximumDelayErrorS = ...
    max(abs(phaseDelayErrorZX(:)));

maximumPhaseErrorRad = ...
    omegaRadS * maximumDelayErrorS;

%% Spectrum

powerSpectrumZX = abs(fftshift(fft2(fieldZX))).^2;
normalizedPowerZX = powerSpectrumZX ./ max(powerSpectrumZX(:));

powerDbZX = 10*log10(normalizedPowerZX + eps);

Nx = numel(xM);
Nz = numel(zM);

kxRadM = ...
    2*pi .* ((-floor(Nx/2)):(ceil(Nx/2)-1)) ./ ...
    (Nx * dxM);

kzRadM = ...
    2*pi .* ((-floor(Nz/2)):(ceil(Nz/2)-1)) ./ ...
    (Nz * dzM);

[~, linearPeakIndex] = max(powerSpectrumZX(:));

[peakZIndex, peakXIndex] = ind2sub( ...
    size(powerSpectrumZX), ...
    linearPeakIndex);

detectedKxRadM = kxRadM(peakXIndex);
detectedKzRadM = kzRadM(peakZIndex);

referenceWavenumberRadM = omegaRadS / csMps;

expectedKxRadM = ...
    referenceWavenumberRadM * directionXYZ(1);

expectedKzRadM = ...
    referenceWavenumberRadM * directionXYZ(3);

expectedProjectedMagnitudeRadM = ...
    referenceWavenumberRadM * ...
    hypot(directionXYZ(1), directionXYZ(3));

detectedProjectedMagnitudeRadM = ...
    hypot(detectedKxRadM, detectedKzRadM);

relativeProjectedMagnitudeError = ...
    abs( ...
        detectedProjectedMagnitudeRadM - ...
        expectedProjectedMagnitudeRadM) ./ ...
    expectedProjectedMagnitudeRadM;

%% Report

fprintf("\nProjected-3D homogeneous Eikonal diagnostic\n");
fprintf("-------------------------------------------\n");
fprintf("Direction [ux uy uz]       : [%.3f %.3f %.3f]\n", ...
    directionXYZ);
fprintf("Projected direction norm   : %.6f\n", ...
    hypot(directionXYZ(1), directionXYZ(3)));
fprintf("Reference k0               : %.6f rad/m\n", ...
    referenceWavenumberRadM);
fprintf("Expected projected k       : %.6f rad/m\n", ...
    expectedProjectedMagnitudeRadM);
fprintf("Detected projected k       : %.6f rad/m\n", ...
    detectedProjectedMagnitudeRadM);
fprintf("Relative projected-k error : %.4f %%\n", ...
    100 * relativeProjectedMagnitudeError);
fprintf("Maximum delay error        : %.6e s\n", ...
    maximumDelayErrorS);
fprintf("Maximum phase error        : %.6e rad\n", ...
    maximumPhaseErrorRad);
fprintf("Solver iterations          : %d\n", ...
    diagnostics.solver.iterations);
fprintf("Runtime                    : %.4f s\n\n", ...
    runtimeS);

%% Figure

figureHandle = figure( ...
    "Visible", "off", ...
    "Color", "w", ...
    "Position", [100, 100, 1300, 850]);

tiledlayout(2, 2, ...
    "TileSpacing", "compact", ...
    "Padding", "compact");

nexttile;

imagesc(xM*1e3, zM*1e3, phaseDelayZX*1e3);
axis image;
set(gca, "YDir", "normal");
colorbar;
xlabel("x (mm)");
ylabel("z (mm)");
title("Projected-3D phase delay (ms)");

nexttile;

imagesc(xM*1e3, zM*1e3, real(fieldZX));
axis image;
set(gca, "YDir", "normal");
colorbar;
xlabel("x (mm)");
ylabel("z (mm)");
title("Real(U)");

nexttile;

imagesc( ...
    kxRadM/1e3, ...
    kzRadM/1e3, ...
    powerDbZX);

axis image;
set(gca, "YDir", "normal");
colorbar;
clim([-60, 0]);

spectralDisplayLimitRadMm = ...
    1.5 * referenceWavenumberRadM / 1e3;

xlim([-spectralDisplayLimitRadMm, spectralDisplayLimitRadMm]);
ylim([-spectralDisplayLimitRadMm, spectralDisplayLimitRadMm]);

hold on;

spectralAngle = linspace(0, 2*pi, 361);

plot( ...
    referenceWavenumberRadM*cos(spectralAngle)/1e3, ...
    referenceWavenumberRadM*sin(spectralAngle)/1e3, ...
    "--", ...
    "LineWidth", 1);

plot( ...
    expectedProjectedMagnitudeRadM*cos(spectralAngle)/1e3, ...
    expectedProjectedMagnitudeRadM*sin(spectralAngle)/1e3, ...
    ":", ...
    "LineWidth", 1.5);

plot( ...
    expectedKxRadM/1e3, ...
    expectedKzRadM/1e3, ...
    "o", ...
    "MarkerSize", 10, ...
    "LineWidth", 1.5);

plot( ...
    detectedKxRadM/1e3, ...
    detectedKzRadM/1e3, ...
    "x", ...
    "MarkerSize", 10, ...
    "LineWidth", 1.5);

hold off;

xlabel("k_x (rad/mm)");
ylabel("k_z (rad/mm)");
title("Power spectrum (dB)");

legend( ...
    "Reference k_0", ...
    "Expected projected radius", ...
    "Expected peak", ...
    "Detected peak", ...
    "Location", "best");

nexttile;

imagesc(xM*1e3, zM*1e3, phaseDelayErrorZX*1e9);
axis image;
set(gca, "YDir", "normal");
colorbar;
xlabel("x (mm)");
ylabel("z (mm)");
title("Delay error (ns)");

sgtitle(sprintf( ...
    ["Projected-3D homogeneous Eikonal | " + ...
     "u=[%.2f, %.2f, %.2f] | f=%g Hz"], ...
    directionXYZ, ...
    frequencyHz));

figurePath = fullfile( ...
    outputDirectory, ...
    "projected3d_homogeneous_field.png");

exportgraphics( ...
    figureHandle, ...
    figurePath, ...
    "Resolution", 180);

close(figureHandle);

summaryTable = table( ...
    directionXYZ(1), ...
    directionXYZ(2), ...
    directionXYZ(3), ...
    frequencyHz, ...
    csMps, ...
    referenceWavenumberRadM, ...
    expectedProjectedMagnitudeRadM, ...
    detectedProjectedMagnitudeRadM, ...
    relativeProjectedMagnitudeError, ...
    maximumDelayErrorS, ...
    maximumPhaseErrorRad, ...
    diagnostics.solver.iterations, ...
    runtimeS, ...
    "VariableNames", { ...
        "ux", ...
        "uy", ...
        "uz", ...
        "frequency_hz", ...
        "cs_m_s", ...
        "reference_k_rad_m", ...
        "expected_projected_k_rad_m", ...
        "detected_projected_k_rad_m", ...
        "relative_projected_k_error", ...
        "maximum_delay_error_s", ...
        "maximum_phase_error_rad", ...
        "solver_iterations", ...
        "runtime_s"});

writetable( ...
    summaryTable, ...
    fullfile(outputDirectory, "summary.csv"));

fprintf("Saved figure: %s\n", figurePath);
