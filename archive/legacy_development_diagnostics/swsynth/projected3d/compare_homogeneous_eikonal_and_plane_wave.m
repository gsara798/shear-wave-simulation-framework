%% Compare homogeneous projected-3D Eikonal and plane-wave propagation

clear;
close all;

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(fileparts(scriptDirectory));
addpath(fullfile(repositoryRoot, "src"));

configDirectory = fullfile( ...
    repositoryRoot, ...
    "configs", ...
    "swsynth", ...
    "validation", ...
    "homogeneous_eikonal_vs_plane_wave");

outputDirectory = fullfile( ...
    repositoryRoot, ...
    "outputs", ...
    "diagnostics", ...
    "homogeneous_eikonal_vs_plane_wave");

if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

singleEikonal = runJson(fullfile( ...
    configDirectory, "single_eikonal.json"));

singlePlane = runJson(fullfile( ...
    configDirectory, "single_plane_wave.json"));

diffuseEikonal = runJson(fullfile( ...
    configDirectory, "diffuse32_eikonal.json"));

diffusePlane = runJson(fullfile( ...
    configDirectory, "diffuse32_plane_wave.json"));

xM = singleEikonal.medium.x_m;
zM = singleEikonal.medium.z_m;

dxM = mean(diff(xM));
dzM = mean(diff(zM));

frequencyHz = singleEikonal.wavefield.frequency_hz;
csMps = singleEikonal.config.medium.background_cs_m_s;
expectedKRadM = 2*pi*frequencyHz/csMps;

%% Direct field comparison after complex scaling

[singlePlaneAlignedZX, singleComplexScale] = ...
    alignComplexField( ...
        singleEikonal.wavefield.U_zx, ...
        singlePlane.wavefield.U_zx);

singleRelativeError = ...
    relativeComplexError( ...
        singleEikonal.wavefield.U_zx, ...
        singlePlaneAlignedZX);

singleCorrelation = ...
    complexCorrelation( ...
        singleEikonal.wavefield.U_zx, ...
        singlePlaneAlignedZX);

[diffusePlaneAlignedZX, diffuseComplexScale] = ...
    alignComplexField( ...
        diffuseEikonal.wavefield.U_zx, ...
        diffusePlane.wavefield.U_zx);

diffuseRelativeError = ...
    relativeComplexError( ...
        diffuseEikonal.wavefield.U_zx, ...
        diffusePlaneAlignedZX);

diffuseCorrelation = ...
    complexCorrelation( ...
        diffuseEikonal.wavefield.U_zx, ...
        diffusePlaneAlignedZX);

%% Power spectra

[singleEikonalPower, kxRadM, kzRadM] = ...
    fieldPowerSpectrum( ...
        singleEikonal.wavefield.U_zx, ...
        dxM, ...
        dzM);

singlePlanePower = ...
    fieldPowerSpectrum( ...
        singlePlane.wavefield.U_zx, ...
        dxM, ...
        dzM);

diffuseEikonalPower = ...
    fieldPowerSpectrum( ...
        diffuseEikonal.wavefield.U_zx, ...
        dxM, ...
        dzM);

diffusePlanePower = ...
    fieldPowerSpectrum( ...
        diffusePlane.wavefield.U_zx, ...
        dxM, ...
        dzM);

singleEikonalPeak = dominantSpectralPeak( ...
    singleEikonalPower, kxRadM, kzRadM);

singlePlanePeak = dominantSpectralPeak( ...
    singlePlanePower, kxRadM, kzRadM);

diffusePowerCorrelation = normalizedPowerCorrelation( ...
    diffuseEikonalPower, ...
    diffusePlanePower);

%% Spectral entropy

entropyOptions = struct( ...
    "AngularBinCount", 36, ...
    "RadialBinCount", 32, ...
    "MinimumRadiusRadM", 0.2*expectedKRadM, ...
    "MaximumRadiusRadM", 1.5*expectedKRadM, ...
    "HalfPlane", "all");

diffuseEikonalEntropy = ...
    swsynth.metrics.computeSpectralEntropy( ...
        diffuseEikonalPower, ...
        kxRadM, ...
        kzRadM, ...
        entropyOptions);

diffusePlaneEntropy = ...
    swsynth.metrics.computeSpectralEntropy( ...
        diffusePlanePower, ...
        kxRadM, ...
        kzRadM, ...
        entropyOptions);

%% Summary

summary = table( ...
    expectedKRadM, ...
    singleEikonalPeak.radius_rad_m, ...
    singlePlanePeak.radius_rad_m, ...
    singleRelativeError, ...
    singleCorrelation, ...
    diffuseRelativeError, ...
    diffuseCorrelation, ...
    diffusePowerCorrelation, ...
    diffuseEikonalEntropy.angular_entropy, ...
    diffusePlaneEntropy.angular_entropy, ...
    diffuseEikonalEntropy.radial_entropy, ...
    diffusePlaneEntropy.radial_entropy, ...
    abs(singleComplexScale), ...
    angle(singleComplexScale), ...
    abs(diffuseComplexScale), ...
    angle(diffuseComplexScale), ...
    VariableNames=[ ...
        "expected_k_rad_m", ...
        "single_eikonal_peak_k_rad_m", ...
        "single_plane_peak_k_rad_m", ...
        "single_relative_complex_error", ...
        "single_complex_correlation", ...
        "diffuse_relative_complex_error", ...
        "diffuse_complex_correlation", ...
        "diffuse_power_correlation", ...
        "diffuse_eikonal_angular_entropy", ...
        "diffuse_plane_angular_entropy", ...
        "diffuse_eikonal_radial_entropy", ...
        "diffuse_plane_radial_entropy", ...
        "single_alignment_amplitude", ...
        "single_alignment_phase_rad", ...
        "diffuse_alignment_amplitude", ...
        "diffuse_alignment_phase_rad"]);

disp(summary);

writetable( ...
    summary, ...
    fullfile(outputDirectory, "comparison_summary.csv"));

%% Figure

figureHandle = figure( ...
