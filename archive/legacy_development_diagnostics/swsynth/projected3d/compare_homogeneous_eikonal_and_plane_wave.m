%% Local functions

function result = runJson(path)

requested = jsondecode(fileread(path));
result = swsynth.run(requested);

end

function [alignedZX, scale] = alignComplexField(referenceZX, testZX)

referenceVector = referenceZX(:);
testVector = testZX(:);

denominator = sum(abs(testVector).^2);

if denominator <= eps
    error( ...
        "swsynth:ZeroValidationField", ...
        "Cannot align a zero-valued validation field.");
end

scale = ...
    sum(conj(testVector).*referenceVector) / denominator;

alignedZX = scale .* testZX;

end

function value = relativeComplexError(referenceZX, testZX)

value = ...
    norm(testZX(:) - referenceZX(:)) / ...
    norm(referenceZX(:));

end

function value = complexCorrelation(referenceZX, testZX)

numerator = abs(sum( ...
    conj(referenceZX(:)) .* testZX(:)));

denominator = ...
    norm(referenceZX(:)) * norm(testZX(:));

value = numerator / denominator;

end

function [powerZX, kxRadM, kzRadM] = ...
        fieldPowerSpectrum(fieldZX, dxM, dzM)

[nz, nx] = size(fieldZX);

windowX = ...
    0.5 - 0.5*cos(2*pi*(0:nx-1)/(nx-1));

windowZ = ...
    0.5 - 0.5*cos(2*pi*(0:nz-1)/(nz-1));

windowZX = windowZ(:) * windowX(:).';

spectrumZX = fftshift(fft2(fieldZX .* windowZX));
powerZX = abs(spectrumZX).^2;

maximumPower = max(powerZX(:));

if maximumPower > 0
    powerZX = powerZX ./ maximumPower;
end

kxRadM = ...
    2*pi .* ...
    ((-floor(nx/2)):(ceil(nx/2)-1)) ./ ...
    (nx*dxM);

kzRadM = ...
    2*pi .* ...
    ((-floor(nz/2)):(ceil(nz/2)-1)) ./ ...
    (nz*dzM);

end

function peak = dominantSpectralPeak(powerZX, kxRadM, kzRadM)

[~, linearIndex] = max(powerZX(:));
[kzIndex, kxIndex] = ind2sub(size(powerZX), linearIndex);

peak = struct();
peak.kx_rad_m = kxRadM(kxIndex);
peak.kz_rad_m = kzRadM(kzIndex);
peak.radius_rad_m = hypot( ...
    peak.kx_rad_m, ...
    peak.kz_rad_m);

end

function value = normalizedPowerCorrelation(powerA, powerB)

a = powerA(:) - mean(powerA(:));
b = powerB(:) - mean(powerB(:));

denominator = norm(a)*norm(b);

if denominator <= eps
    value = NaN;
else
    value = dot(a,b)/denominator;
end

end

function plotField(xM, zM, fieldZX, plotTitle)

nexttile;

imagesc(xM*1e3, zM*1e3, real(fieldZX));

axis image;
set(gca, "YDir", "normal");

xlabel("x (mm)");
ylabel("z (mm)");
title(plotTitle);
colorbar;

end

function plotSpectrum( ...
        powerZX, normalizedKX, normalizedKZ, plotTitle)

nexttile;

imagesc(normalizedKX, normalizedKZ, powerZX);

axis image;
set(gca, "YDir", "normal");

xlim([-1.5,1.5]);
ylim([-1.5,1.5]);
clim([0,1]);

xlabel("k_x/k_0");
ylabel("k_z/k_0");
title(plotTitle);
colorbar;

end
